export function getFallbackResponse(message: string, mode: string = 'onamFriend'): string {
  const lower = message.toLowerCase();
  
  for (const item of fallbackResponses) {
    if (item.keywords.some(k => lower.includes(k))) {
      const responses = item.responses;
      return responses[Math.floor(Math.random() * responses.length)];
    }
  }

  // Mode-specific defaults
  const modeDefaults: Record<string, string[]> = {
    mischief: [
      "Ayyoo, that question! 😂 Njan cheriya aal aanu, but even I don't know everything! Try asking about Onam, Mahabali, or my legendary three steps! 👣😏",
      "Hehe... tricky question! 🤭 Njan moonnu adi kond universe cover cheythu, but your question covers more than the universe! 😂 Ask me about Kerala culture instead!"
    ],
    storyteller: [
      "Hmm... that is a tale I have not yet told. 📖 But perhaps you could ask me about Mahabali, the three steps, or the festivals of Kerala? Every story has its season...",
    ],
    wise: [
      "Valippam alla pradhanam — buddhi use cheyyuka. 😌 That question needs deeper thought. Ask me about Onam, Kerala wisdom, or the story of Mahabali, and I shall guide you.",
    ],
    game: [
      "Ooh, stepping outside the game zone! 🎮 Let's stay on track — I have amazing Onam quizzes and riddles for you! Ready for a challenge? 😏",
    ],
    wishes: [
      "🌸 May Onam bring you all the joy in the world! Mahabali's blessings, Vamanan's love, and Kerala's warmth — all yours! 🌼 Want a personalized wish? Tell me your name! 😌",
    ],
    default: [
      "Interesting question! 🤔 Njan ithine patthi ariyilla, but njan Onam, Kerala culture, Mahabali, and all things wonderful about this festival know very well! Try asking about those! 🌼😌",
      "Ayyoo... that one stumped me! 😅 But ask me about Onam, sadya, pookalam, stories, or my famous three steps — I'll shine! 😏🌸",
      "Hmm 🤔 Ingi ingane... njan definitely know about Onam, Mahabali, Kerala traditions, and more! Ask me something in that space and watch me go! 😌🌼"
    ]
  };

  const options = modeDefaults[mode] || modeDefaults.default;
  return options[Math.floor(Math.random() * options.length)];
}

